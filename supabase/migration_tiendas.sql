-- Tabla de tiendas (catálogo maestro para autocompletar en los formularios)
create table if not exists public.tiendas (
  id uuid primary key default gen_random_uuid(),
  nombre text not null unique,
  ceco text,
  departamento text,
  created_at timestamptz not null default now()
);

alter table public.tiendas enable row level security;

create policy "tiendas_select" on public.tiendas for select using (true);
create policy "tiendas_insert" on public.tiendas for insert with check (true);
create policy "tiendas_update" on public.tiendas for update using (true);

-- Sincronización en tiempo real (para que la lista se actualice en todos los dispositivos)
alter publication supabase_realtime add table public.tiendas;

